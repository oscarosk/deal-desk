"""Generate the order form, but only for terms that a person with enough
authority has approved.

The approval file records who approved and what they approved. This script
reruns the pricing check on exactly those terms and refuses when:
  - the terms break the margin floor or another hard rule, or
  - the approver's role is below the role the terms need.

Usage:
    python tools/order_form.py data/deals/northwind.json approval.json [-o out.md]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pricing import APPROVERS, DEFAULT_PRICE_LIST, check_deal, load_json  # noqa: E402

REQUIRED = ("deal_id", "approved_by", "role", "approved_at", "terms")


class ApprovalError(Exception):
    pass


def validate(deal: dict, approval: dict, prices: dict) -> dict:
    missing = [k for k in REQUIRED if k not in approval]
    if missing:
        raise ApprovalError(f"approval is missing {', '.join(missing)}")
    if approval["deal_id"] != deal["deal_id"]:
        raise ApprovalError(
            f"approval is for {approval['deal_id']}, not {deal['deal_id']}")
    role = approval["role"]
    if role not in APPROVERS:
        raise ApprovalError(f"unknown role {role!r}")

    approved = {**deal, **approval["terms"]}
    result = check_deal(approved, prices)
    if result["verdict"] == "reject":
        raise ApprovalError("approved terms break a hard rule: " + "; ".join(result["reasons"]))
    if APPROVERS.index(role) < APPROVERS.index(result["approver"]):
        raise ApprovalError(
            f"these terms need {result['approver']}, but {approval['approved_by']} "
            f"approved as {role}")
    return result


def render(deal: dict, approval: dict, result: dict, currency: str) -> str:
    clauses = approval.get("clauses") or ["Standard Lumen Analytics terms apply."]
    lines = [
        f"# Order form {deal['deal_id']}",
        "",
        "> Generated by the Deal Desk demo. Fictional company, customer and prices.",
        "",
        f"**Supplier:** {result['company']}  ",
        f"**Customer:** {deal['customer']}",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Plan | {result['plan'].title()} |",
        f"| Seats | {result['seats']} |",
        f"| Term | {result['term_months']} months |",
        f"| Discount | {result['requested_discount_pct']:g}% |",
        f"| Price per seat per year | {currency} {result['net_per_seat_year']:,.2f} |",
        f"| Total contract value | {currency} {result['net_total']:,.2f} |",
        f"| Payment terms | {result['payment_terms']} |",
        "",
        "## Agreed clauses",
        "",
        *[f"- {c}" for c in clauses],
        "",
        "## Approval",
        "",
        f"Approved by **{approval['approved_by']}** ({approval['role'].replace('_', ' ')}) "
        f"at {approval['approved_at']}.",
    ]
    if approval.get("switch_message"):
        lines.append(f"Approval message in Switch: {approval['switch_message']}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("deal", type=Path)
    parser.add_argument("approval", type=Path)
    parser.add_argument("--prices", type=Path, default=DEFAULT_PRICE_LIST)
    parser.add_argument("-o", "--output", type=Path)
    args = parser.parse_args(argv)
    try:
        deal, approval = load_json(args.deal), load_json(args.approval)
        prices = load_json(args.prices)
        result = validate(deal, approval, prices)
    except (ApprovalError, ValueError, KeyError, OSError, json.JSONDecodeError) as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return 1
    text = render(deal, approval, result, prices["currency"])
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
        print(f"Wrote {args.output}")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
